export function crearTraductor(idioma) {
  const tabla = TEXTOS[idioma] ?? TEXTOS.es;
  return (clave, vars = {}) =>
    (tabla[clave] ?? TEXTOS.es[clave] ?? clave).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
